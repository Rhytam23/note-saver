// Keeps two kinds of generated copies in step. `telegram/` is the single source
// of truth for everything Telegram; this script produces the parts other tools
// insist on finding elsewhere.
//
//  1. App logic the bot reuses  (src/  ->  telegram/bot/_shared/generated/)
//     The Supabase bundler can't reliably import from src/, so the pure app
//     modules (flashcards, note links, templates, lock prefix, types) are copied.
//
//  2. Deployable copies  (telegram/  ->  supabase/)
//     Supabase only deploys functions from supabase/functions/<name>/ and only
//     applies migrations from supabase/migrations/, so:
//       telegram/bot/**        -> supabase/functions/telegram-bot/**
//       telegram/database/*.sql -> supabase/migrations/*.sql
//
// A Vitest test fails if any copy is stale.
//
//   node telegram/scripts/sync-bot-shared.mjs          write the copies
//   node telegram/scripts/sync-bot-shared.mjs --check  exit 1 if any copy is stale
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, rmSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const GENERATED_DIR = join(ROOT, 'telegram', 'bot', '_shared', 'generated');
const BOT_SRC = join(ROOT, 'telegram', 'bot');
const BOT_DEPLOY = join(ROOT, 'supabase', 'functions', 'telegram-bot');
const DB_SRC = join(ROOT, 'telegram', 'database');
const DB_DEPLOY = join(ROOT, 'supabase', 'migrations');
const HEADER = '// GENERATED by telegram/scripts/sync-bot-shared.mjs from src/ - DO NOT EDIT. Run `npm run bot:sync`.\n';

const normalise = (text) => text.replace(/\r\n/g, '\n');
const read = (rel) => normalise(readFileSync(join(ROOT, rel), 'utf8'));

/** Every file under `dir` (relative, forward-slash paths). */
function listFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((e) => e.isFile())
    .map((e) => relative(dir, join(e.parentPath ?? e.path, e.name)).split('\\').join('/'));
}

/** filename -> content for telegram/bot/_shared/generated/. */
export function buildGenerated() {
  const retarget = (source) => source.replace(/from '\.\.\/types'/g, "from './types.ts'");

  const lockMatch = read('src/services/noteLock.ts').match(/export const LOCK_PREFIX = '([^']+)';/);
  if (!lockMatch) throw new Error('LOCK_PREFIX not found in src/services/noteLock.ts');

  return {
    'types.ts': HEADER + read('src/types.ts'),
    'flashcards.ts': HEADER + retarget(read('src/services/flashcards.ts')),
    'noteLinks.ts': HEADER + retarget(read('src/services/noteLinks.ts')),
    'noteTemplates.ts': HEADER + read('src/services/noteTemplates.ts'),
    'lockPrefix.ts': HEADER + `export const LOCK_PREFIX = '${lockMatch[1]}';\n`,
  };
}

/**
 * absolute target path -> content, for the deployable copies. Reads the
 * (already generated) telegram/bot tree, so run after the generated step.
 */
export function buildDeployCopies() {
  const out = {};
  for (const file of listFiles(BOT_SRC)) {
    out[join(BOT_DEPLOY, file)] = normalise(readFileSync(join(BOT_SRC, file), 'utf8'));
  }
  out[join(BOT_DEPLOY, 'README.md')] = DEPLOY_README;
  for (const file of listFiles(DB_SRC)) {
    out[join(DB_DEPLOY, file)] = normalise(readFileSync(join(DB_SRC, file), 'utf8'));
  }
  return out;
}

const DEPLOY_README = [
  '# telegram-bot (deploy copy)',
  '',
  'Do not edit anything in this folder. It is generated from `telegram/bot/`',
  '(and the database file from `telegram/database/`) by `npm run bot:sync`,',
  'because Supabase only deploys functions from `supabase/functions/`.',
  '',
  'Edit `telegram/`, run `npm run bot:sync`, then deploy:',
  '',
  '    supabase functions deploy telegram-bot --no-verify-jwt',
  '',
  'See `telegram/README.md`.',
  '',
].join('\n');

/** Files in the function's deploy folder that no longer exist in telegram/bot/. */
export function findOrphans() {
  const wanted = new Set([...listFiles(BOT_SRC), 'README.md']);
  return listFiles(BOT_DEPLOY).filter((f) => !wanted.has(f)).map((f) => join(BOT_DEPLOY, f));
}

function main() {
  const check = process.argv.includes('--check');
  let stale = false;

  const sync = (path, content) => {
    const current = existsSync(path) ? normalise(readFileSync(path, 'utf8')) : null;
    if (current === content) return;
    const shown = relative(ROOT, path).split('\\').join('/');
    if (check) {
      console.error(`stale: ${shown}`);
      stale = true;
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
      console.log(`wrote ${shown}`);
    }
  };

  for (const [name, content] of Object.entries(buildGenerated())) sync(join(GENERATED_DIR, name), content);
  for (const [path, content] of Object.entries(buildDeployCopies())) sync(path, content);
  for (const orphan of findOrphans()) {
    const shown = relative(ROOT, orphan).split('\\').join('/');
    if (check) {
      console.error(`orphan (not in telegram/bot): ${shown}`);
      stale = true;
    } else {
      rmSync(orphan);
      console.log(`removed ${shown}`);
    }
  }
  if (check && stale) process.exit(1);
}

// Only run when invoked directly, so tests can import the builders.
if (process.argv[1] && fileURLToPath(import.meta.url) === join(process.argv[1])) main();
