// Copies the pure app modules the Telegram bot reuses into
// supabase/functions/_shared/generated/. The Supabase function bundler can't
// reliably import from src/, so this keeps ONE source of truth (src/) and a
// generated mirror. A Vitest parity test fails if the mirror goes stale.
//
//   node scripts/sync-bot-shared.mjs          write the mirror
//   node scripts/sync-bot-shared.mjs --check  exit 1 if the mirror is stale
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'supabase', 'functions', '_shared', 'generated');
const HEADER = '// GENERATED by scripts/sync-bot-shared.mjs from src/ - DO NOT EDIT. Run `npm run bot:sync`.\n';

const read = (rel) => readFileSync(join(root, rel), 'utf8').replace(/\r\n/g, '\n');

/** name -> generated file content. Deno needs explicit .ts extensions on relative imports. */
export function buildGenerated() {
  const retarget = (source) => source.replace(/from '\.\.\/types'/g, "from './types.ts'");

  const lockSource = read('src/services/noteLock.ts');
  const lockMatch = lockSource.match(/export const LOCK_PREFIX = '([^']+)';/);
  if (!lockMatch) throw new Error('LOCK_PREFIX not found in src/services/noteLock.ts');

  return {
    'types.ts': HEADER + read('src/types.ts'),
    'flashcards.ts': HEADER + retarget(read('src/services/flashcards.ts')),
    'noteLinks.ts': HEADER + retarget(read('src/services/noteLinks.ts')),
    'noteTemplates.ts': HEADER + read('src/services/noteTemplates.ts'),
    'lockPrefix.ts': HEADER + `export const LOCK_PREFIX = '${lockMatch[1]}';\n`,
  };
}

export const GENERATED_DIR = outDir;

function main() {
  const generated = buildGenerated();
  const check = process.argv.includes('--check');
  let stale = false;

  mkdirSync(outDir, { recursive: true });
  for (const [name, content] of Object.entries(generated)) {
    const path = join(outDir, name);
    const current = existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current === content) continue;
    if (check) {
      console.error(`stale: supabase/functions/_shared/generated/${name}`);
      stale = true;
    } else {
      writeFileSync(path, content);
      console.log(`wrote supabase/functions/_shared/generated/${name}`);
    }
  }
  if (check && stale) process.exit(1);
}

// Only run when invoked directly, so the parity test can import buildGenerated().
if (process.argv[1] && fileURLToPath(import.meta.url) === join(process.argv[1])) main();
